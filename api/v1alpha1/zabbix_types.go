// DatabaseSpec selects the PostgreSQL database backing the deployment.
// Exactly one provider must be configured.
// +kubebuilder:validation:XValidation:message="exactly one of cnpg or external must be set",rule="has(self.cnpg) != has(self.external)"
type DatabaseSpec struct {
	// cnpg references a CloudNativePG Cluster that provides the database.
	// The operator reads the Cluster's app-user Secret (<clusterName>-app)
	// for connection details. Preferred provider (high availability,
	// backups, and version upgrades are delegated to CloudNativePG).
	// +optional
	CNPG *CNPGDatabaseSpec `json:"cnpg,omitempty"`

	// external references an existing Secret with PostgreSQL connection
	// details for a database managed outside the operator. The Secret must
	// contain the keys host, port, user, password, and dbname — the same
	// shape generated by CloudNativePG.
	// +optional
	External *ExternalDatabaseSpec `json:"external,omitempty"`
}

// CNPGDatabaseSpec references a CloudNativePG Cluster resource.
type CNPGDatabaseSpec struct {
	// clusterName is the name of an existing CloudNativePG Cluster in the
	// same namespace as the Zabbix resource.
	// +required
	ClusterName string `json:"clusterName"`
}

// ExternalDatabaseSpec references a user-provided database Secret.
type ExternalDatabaseSpec struct {
	// secretName is the name of a Secret (same namespace) containing the
	// PostgreSQL connection details under the keys host, port, user,
	// password, and dbname.
	// +required
	SecretName string `json:"secretName"`
}

// ImageSpec overrides the container image of a component. By default the
// official images are used with the tag derived from spec.version
// (e.g. zabbix/zabbix-server-pgsql:ubuntu-8.0).
type ImageSpec struct {
	// repository replaces the default image repository.
	// +optional
	Repository string `json:"repository,omitempty"`

	// tag replaces the tag derived from spec.version.
	// +optional
	Tag string `json:"tag,omitempty"`

	// pullPolicy is the image pull policy.
	// +kubebuilder:validation:Enum=Always;IfNotPresent;Never
	// +optional
	PullPolicy corev1.PullPolicy `json:"pullPolicy,omitempty"`
}

// ServerSpec configures the Zabbix server. Native high availability is
// enabled by setting replicas greater than 1; all server replicas share
// the database selected in spec.database.
type ServerSpec struct {
	// replicas is the number of Zabbix server pods. 1 runs the server in
	// standalone mode; more than 1 enables native HA (one active node,
	// the rest standby, heartbeat and failover handled by Zabbix).
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the server container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the server container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// agent configures the Zabbix agent 2 sidecar running in each server
	// pod (self-monitoring). Enabled by default.
	// +optional
	Agent *AgentSidecarSpec `json:"agent,omitempty"`
}

// AgentSidecarSpec configures the agent 2 sidecar.
type AgentSidecarSpec struct {
	// enabled runs an agent 2 sidecar in each server pod.
	// +optional
	Enabled *bool `json:"enabled,omitempty"`

	// image overrides the agent 2 sidecar image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`
}

// APISpec configures how the operator reaches the Zabbix API (served by
// the frontend at /api_jsonrpc.php) for control-plane operations such as
// server HA node state observation.
type APISpec struct {
	// tokenSecretRef references a Secret (same namespace) whose key holds
	// a Zabbix API token. The token must belong to a user with permission
	// to read HA node state (hanode.get). Create it in the frontend under
	// Users → API tokens. Required when server.replicas > 1.
	// +required
	TokenSecretRef corev1.SecretKeySelector `json:"tokenSecretRef"`
}

// FrontendSpec configures the Zabbix frontend.
type FrontendSpec struct {
	// replicas is the number of frontend pods.
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the frontend container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the frontend container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// env exposes additional environment variables to the frontend
	// container (e.g. PHP settings).
	// +optional
	Env []corev1.EnvVar `json:"env,omitempty"`

	// service configures the Service fronting the frontend (the
	// user-facing entry). In-cluster access is a ClusterIP Service by
	// default; external exposure (NodePort/LoadBalancer) is opt-in. Any
	// ingress routing on top stays user-managed: the operator owns the
	// Service, not the traffic stack above it.
	// +optional
	Service *FrontendServiceSpec `json:"service,omitempty"`
}

// FrontendServiceSpec configures the frontend Service.
type FrontendServiceSpec struct {
	// type is the exposure of the frontend Service. ClusterIP (the
	// default) serves in-cluster traffic only; NodePort and LoadBalancer
	// expose the frontend outside the cluster (the assigned NodePort is
	// allocation-controlled by the cluster, not pinned here).
	// +kubebuilder:validation:Enum=ClusterIP;NodePort;LoadBalancer
	// +optional
	Type *corev1.ServiceType `json:"type,omitempty"`

	// annotations are added to the frontend Service (e.g. cloud
	// load-balancer settings).
	// +optional
	Annotations map[string]string `json:"annotations,omitempty"`
}

// WebServiceSpec configures the Zabbix web service, which the server uses
// to generate scheduled reports.
type WebServiceSpec struct {
	// replicas is the number of web service pods.
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the web service container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the web service container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`
}

// ClusterMetricsSpec configures the ingestion of Kubernetes cluster
// metrics into this Zabbix instance via the official "Kubernetes
// Cluster by HTTP" template: the operator deploys a kube-state-metrics
// endpoint, provisions a scoped service-account token, and creates the
// Zabbix host with the template linked. Requires spec.api (the host is
// managed through the Zabbix API).
type ClusterMetricsSpec struct {
	// clusterName is the Zabbix host name for the monitored Kubernetes
	// cluster (one host per cluster). The operator creates or adopts a
	// host with this name.
	// +required
	ClusterName string `json:"clusterName"`

	// tlsVerify sets the {$HTTP.TLS.VERIFY} macro on the host. "full"
	// requires the Zabbix server container to trust the Kubernetes API
	// server CA; "none" skips certificate verification. The default is
	// "none" (works out of the box; switch to "full" after mounting the
	// cluster CA into the server).
	// +kubebuilder:validation:Enum=full;none
	// +kubebuilder:default=none
	// +optional
	TLSVerify string `json:"tlsVerify,omitempty"`

	// kubeStateMetrics, when set, has the operator deploy and manage a
	// kube-state-metrics workload (Deployment + Service) in the
	// placement namespace. The Service is named <namePrefix>-kube-state-metrics
	// so the template's endpoint discovery regex matches it. When unset,
	// the template discovers an existing kube-state-metrics whose
	// Endpoints name ends in "kube-state-metrics" and whose port is
	// named "http"/"https".
	// +optional
	KubeStateMetrics *KubeStateMetricsSpec `json:"kubeStateMetrics,omitempty"`

	// namespace overrides where the derived cluster-metrics objects
	// (managed kube-state-metrics workload, monitor identity, token
	// Secret) are deployed. The namespace must already exist. The
	// default is the Zabbix resource's own namespace.
	// +optional
	// +kubebuilder:validation:Pattern=`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`
	// +kubebuilder:validation:MaxLength=63
	Namespace string `json:"namespace,omitempty"`

	// namePrefix overrides the prefix of the derived cluster-metrics
	// object names: <namePrefix>-kube-state-metrics (Deployment,
	// Service, ServiceAccount), <namePrefix>-kube-monitor (monitor
	// ServiceAccount) and <namePrefix>-kube-monitor-token (token
	// Secret). The suffixes stay fixed — the template's kube-state-metrics
	// discovery regex matches names ENDING in "kube-state-metrics".
	// The default prefix is the Zabbix resource's name. A change of
	// placement while the feature is enabled is ignored: placement is
	// recorded in the status at enablement and honored until the
	// feature is disabled and re-enabled.
	// +optional
	// +kubebuilder:validation:Pattern=`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`
	// +kubebuilder:validation:MaxLength=40
	NamePrefix string `json:"namePrefix,omitempty"`
}

// KubeStateMetricsSpec configures the operator-managed kube-state-metrics
// endpoint.
type KubeStateMetricsSpec struct {
	// image overrides the kube-state-metrics image. The default is the
	// lab-verified registry.k8s.io/kube-state-metrics/kube-state-metrics
	// image at a fixed version.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the kube-state-metrics container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`
}

// ZabbixSpec defines the desired state of Zabbix.
// +kubebuilder:validation:XValidation:message="api.tokenSecretRef is required when server.replicas > 1: HA mode needs the Zabbix API for active-node routing",rule="!(has(self.server) && has(self.server.replicas) && self.server.replicas > 1) || (has(self.api) && has(self.api.tokenSecretRef))"
// +kubebuilder:validation:XValidation:message="clusterMetrics requires spec.api (api.tokenSecretRef): the cluster host is managed through the Zabbix API",rule="!has(self.clusterMetrics) || (has(self.api) && has(self.api.tokenSecretRef))"
type ZabbixSpec struct {
	// version is the Zabbix release to deploy (e.g. "8.0" or "7.0"). It
	// selects the official container image tags and must match the
	// database schema version.
	// +kubebuilder:validation:Pattern=`^[0-9]+\.[0-9]+$`
	// +required
	Version string `json:"version"`

	// database selects the PostgreSQL database backing this deployment.
	// +required
	Database DatabaseSpec `json:"database"`

	// server configures the Zabbix server.
	// +optional
	Server ServerSpec `json:"server,omitempty"`

	// api configures the operator's access to the Zabbix API. Required
	// when the server runs in HA mode (server.replicas > 1): the operator
	// maintains active-node routing from the HA node state.
	// +optional
	API *APISpec `json:"api,omitempty"`

	// frontend configures the Zabbix frontend. Deployed by default.
	// +optional
	Frontend *FrontendSpec `json:"frontend,omitempty"`

	// webService configures the Zabbix web service. Deployed by default.
	// +optional
	WebService *WebServiceSpec `json:"webService,omitempty"`

	// clusterMetrics turns on ingestion of Kubernetes cluster metrics
	// into this Zabbix instance (kube-state-metrics endpoint + "Kubernetes
	// Cluster by HTTP" template host). Optional; off by default.
	// +optional
	ClusterMetrics *ClusterMetricsSpec `json:"clusterMetrics,omitempty"`

	// telemetryStorage routes item history and APM telemetry through
	// ClickHouse instead of the SQL database (Zabbix 8.0+; ignored on
	// older versions). Optional; off by default.
	// +optional
	TelemetryStorage *TelemetryStorageSpec `json:"telemetryStorage,omitempty"`
}

// TelemetryStorageSpec configures ClickHouse as the history storage
// provider and telemetry data source. The operator wires the official
// image entrypoints (ZBX_HISTORYPROVIDER_<N> / ZBX_TELEMETRYPROVIDER_<N>,
// verified against zabbix-docker 8.0); credentials are delivered through
// Secret-backed files, never as plain env values.
type TelemetryStorageSpec struct {
	// clickhouse is the ClickHouse endpoint configuration. History is
	// routed server- and frontend-side; the telemetry provider is wired
	// to the server (telemetry query items), the frontend (APM menu) and
	// every operator-managed proxy group (APM collector output).
	// +required
	ClickHouse ClickHouseSpec `json:"clickhouse"`
}

// ClickHouseSpec selects one ClickHouse endpoint, either operator-managed
// (spec.telemetryStorage.clickhouse.managed) or external. In external mode
// a single URL is supported by Zabbix (multi-node clusters need a load
// balancer in front); see the official ClickHouse setup guide.
// +kubebuilder:validation:XValidation:message="endpoint is required unless managed mode is enabled (the managed endpoint is derived)",rule="has(self.managed) || has(self.endpoint)"
// +kubebuilder:validation:XValidation:message="credentialsSecretRef is required unless managed mode is enabled (the managed credentials are operator-generated)",rule="has(self.managed) || has(self.credentialsSecretRef)"
type ClickHouseSpec struct {
	// endpoint is the ClickHouse HTTP interface URL (port 8123), e.g.
	// "http://clickhouse.monitoring.svc:8123". Required unless managed
	// mode is enabled (the managed endpoint is derived from the managed
	// StatefulSet's Service).
	// +kubebuilder:validation:Pattern=`^https?://[a-zA-Z0-9.\-_:]+[0-9]*$`
	// +optional
	Endpoint string `json:"endpoint,omitempty"`

	// managed, when set, has the operator deploy a single-node
	// ClickHouse (StatefulSet + PVC + Service) in the Zabbix resource's
	// namespace, generate its credentials into an operator-owned Secret
	// and wire the Zabbix stack to it. Simplest setup; for production
	// history volumes prefer a managed external cluster behind a load
	// balancer.
	// +optional
	Managed *ClickHouseManagedSpec `json:"managed,omitempty"`

	// database is the ClickHouse database holding the zabbix tables
	// (history_uint, history, ...). Defaults to "zabbix".
	// +optional
	Database string `json:"database,omitempty"`

	// credentialsSecretRef names a Secret carrying the ClickHouse
	// username and password. The operator mounts it read-only and points
	// the image entrypoints at the files. Required unless managed mode
	// is enabled (the managed credentials are operator-generated).
	// +optional
	CredentialsSecretRef ClickHouseCredentials `json:"credentialsSecretRef,omitempty"`

	// valueTypes routes only these item value types to ClickHouse
	// (uint, dbl, str, log, text, json). Empty routes all supported
	// types.
	// +kubebuilder:validation:items:Pattern=`^(uint|dbl|str|log|text|json)$`
	// +optional
	ValueTypes []string `json:"valueTypes,omitempty"`

	// createSchema lets the image entrypoint create the history tables
	// on startup (official _SCHEMA={"create":true} behavior). Set false
	// when the schema was imported manually (e.g. migrated from an SQL
	// database). Defaults to true.
	// +optional
	CreateSchema *bool `json:"createSchema,omitempty"`

	// tls optionally secures the ClickHouse connection with CA / client
	// certificate material from a Secret. External endpoints only: the
	// operator-managed single node is not TLS-terminated.
	// +optional
	TLS *ClickHouseTLS `json:"tls,omitempty"`
}

// ClickHouseManagedSpec configures the operator-managed single-node
// ClickHouse deployment.
type ClickHouseManagedSpec struct {
	// storage size of the ClickHouse data PersistentVolumeClaim.
	// +kubebuilder:default="10Gi"
	// +optional
	Storage resource.Quantity `json:"storage,omitempty"`

	// storageClassName for the data PersistentVolumeClaim. Empty uses
	// the cluster default storage class.
	// +optional
	StorageClassName string `json:"storageClassName,omitempty"`

	// resources for the ClickHouse server container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// image overrides the ClickHouse server image. The default is the
	// official clickhouse/clickhouse-server image at a version inside
	// the range the Zabbix 8.0 requirements list (26.3–26.9).
	// +optional
	Image *ImageSpec `json:"image,omitempty"`
}

// ClickHouseCredentials points at the keys of an existing Secret.
type ClickHouseCredentials struct {
	// secretName is the Secret name.
	// +required
	SecretName string `json:"secretName"`

	// usernameKey is the Secret key holding the username. Defaults to
	// "username".
	// +optional
	UsernameKey string `json:"usernameKey,omitempty"`

	// passwordKey is the Secret key holding the password. Defaults to
	// "password".
	// +optional
	PasswordKey string `json:"passwordKey,omitempty"`
}

// ClickHouseTLS references CA / client certificate / private key inside
// one Secret for the ClickHouse connection.
type ClickHouseTLS struct {
	// secretName is the Secret carrying the TLS material.
	// +required
	SecretName string `json:"secretName"`

	// caKey is the Secret key holding the CA certificate. Defaults to
	// "ca.crt". Omit (empty) to skip CA verification.
	// +optional
	CAKey string `json:"caKey,omitempty"`

	// certKey is the Secret key holding the client certificate.
	// Defaults to "tls.crt".
	// +optional
	CertKey string `json:"certKey,omitempty"`

	// keyKey is the Secret key holding the client private key. Defaults
	// to "tls.key".
	// +optional
	KeyKey string `json:"keyKey,omitempty"`
}

// HANodeStatus is the observed state of one Zabbix server HA node.
type HANodeStatus struct {
	// name is the HA node name (the server pod name in standalone-to-HA
	// transitions managed by the operator).
	// +required
	Name string `json:"name"`

	// status is the Zabbix-reported node status: active, standby,
	// unavailable, stopped, or unknown (a status code outside the
	// documented registry values; never routed to the active Service).
	// +kubebuilder:validation:Enum=active;standby;unavailable;stopped;unknown
	// +required
	Status string `json:"status"`

	// address is the node address as registered in the HA cluster.
	// +optional
	Address string `json:"address,omitempty"`
}

// ServerHAStatus is the observed state of the server HA cluster.
type ServerHAStatus struct {
	// activeNode is the name of the currently active HA node.
	// +optional
	ActiveNode string `json:"activeNode,omitempty"`

	// nodes lists all HA nodes known to the cluster.
	// +optional
	Nodes []HANodeStatus `json:"nodes,omitempty"`
}

// ComponentConditionType is a custom condition type on the Zabbix resource.
type ComponentConditionType string

const (
	// ConditionReady indicates the deployment as a whole is deployed and
	// all its components are ready.
	ConditionReady ComponentConditionType = "Ready"

	// ConditionDatabaseReady indicates the selected database is reachable.
	ConditionDatabaseReady ComponentConditionType = "DatabaseReady"

	// ConditionServerReady indicates the server workload is deployed and
	// its pods are healthy.
	ConditionServerReady ComponentConditionType = "ServerReady"

	// ConditionFrontendReady indicates the frontend workload is deployed
	// and its pods are healthy.
	ConditionFrontendReady ComponentConditionType = "FrontendReady"

	// ConditionWebServiceReady indicates the web service workload is
	// deployed and its pods are healthy.
	ConditionWebServiceReady ComponentConditionType = "WebServiceReady"

	// ConditionClusterMetricsReady indicates the cluster-metrics
	// ingestion (kube-state-metrics endpoint + Zabbix cluster host) is
	// deployed and registered with the server.
	ConditionClusterMetricsReady ComponentConditionType = "ClusterMetricsReady"

	// ConditionTelemetryStorageReady indicates the managed ClickHouse
	// backend (spec.telemetryStorage.clickhouse.managed) is deployed
	// and its pod is healthy.
	ConditionTelemetryStorageReady ComponentConditionType = "TelemetryStorageReady"

	// ConditionDataSourceReady indicates the global APM telemetry data
	// source (the settings.apm_global_db object) is converged on the
	// server through the API — enabled alongside the ClickHouse
	// telemetry storage, cleared when it is removed. Requires spec.api
	// (a token); without one the data source is not managed.
	ConditionDataSourceReady ComponentConditionType = "DataSourceReady"
)

// ZabbixStatus defines the observed state of Zabbix.
type ZabbixStatus struct {
	// observedGeneration is the generation most recently observed by the
	// controller.
	// +optional
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`

	// conditions represent the current state of the Zabbix resource.
	// Custom condition types: DatabaseReady, ServerReady, FrontendReady,
	// WebServiceReady.
	// +listType=map
	// +listMapKey=type
	// +optional
	Conditions []metav1.Condition `json:"conditions,omitempty"`

	// serverHA reports the observed state of the server HA cluster
	// (empty when the server runs in standalone mode).
	// +optional
	ServerHA *ServerHAStatus `json:"serverHA,omitempty"`

	// clusterMetricsHostName records the Zabbix host name registered by
	// the cluster-metrics feature. It is kept on the status so the
	// disable path can still address the host after the feature flag
	// (and with it the spec field) is removed.
	// +optional
	ClusterMetricsHostName string `json:"clusterMetricsHostName,omitempty"`

	// clusterMetricsNamespace records the namespace the cluster-metrics
	// objects were deployed into (spec override or the resource's own
	// namespace at enablement). The disable and deletion paths address
	// the objects through it after the spec field is gone.
	// +optional
	ClusterMetricsNamespace string `json:"clusterMetricsNamespace,omitempty"`

	// clusterMetricsNamePrefix records the name prefix the
	// cluster-metrics objects were created with (spec override or the
	// resource's name at enablement). The disable and deletion paths
	// address the objects through it after the spec field is gone.
	// +optional
	ClusterMetricsNamePrefix string `json:"clusterMetricsNamePrefix,omitempty"`

	// apmDataSourceURL and apmDataSourceDB record the coordinates of
	// the global APM data source the operator last ensured through the
	// API. The disable path (telemetry storage removed) uses them to
	// clear only what the operator itself configured — a data source a
	// user configured manually in the frontend is never touched.
	// +optional
	APMDataSourceURL string `json:"apmDataSourceURL,omitempty"`
	// +optional
	APMDataSourceDB string `json:"apmDataSourceDB,omitempty"`
}

