// Zabbix is the Schema for the zabbixes API. One resource owns one
// complete Zabbix deployment: server, frontend, web service, and their
// database wiring.
type Zabbix struct {
	metav1.TypeMeta `json:",inline"`

	// metadata is a standard object metadata
	// +optional
	metav1.ObjectMeta `json:"metadata,omitzero"`

	// spec defines the desired state of Zabbix
	// +required
	Spec ZabbixSpec `json:"spec"`

	// status defines the observed state of Zabbix
	// +optional
	Status ZabbixStatus `json:"status,omitzero"`
}

// +kubebuilder:object:root=true

// ZabbixList contains a list of Zabbix
type ZabbixList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitzero"`
	Items           []Zabbix `json:"items"`
}

func init() {
	SchemeBuilder.Register(func(s *runtime.Scheme) error {
		s.AddKnownTypes(SchemeGroupVersion, &Zabbix{}, &ZabbixList{})
		return nil
	})
}
