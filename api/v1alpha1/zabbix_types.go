// DatabaseSpec selects the PostgreSQL database backing the deployment.
// Exactly one provider must be configured.
// +kubebuilder:validation:XValidation:message="exactly one of cnpg or external must be set",rule="has(self.cnpg) != has(self.external)"
type DatabaseSpec struct {
	// cnpg references a CloudNativePG Cluster that provides the database.
	// The operator reads the Cluster's app-user Secret (<clusterName>-app)
	// for connection details. Preferred provider (high availability,
	// backups, and version upgrades are delegated to CloudNativePG).
	// +optional
	CNPG *CNPGDatabaseSpec `json:"cnpg,omitempty"`

	// external references an existing Secret with PostgreSQL connection
	// details for a database managed outside the operator. The Secret must
	// contain the keys host, port, user, password, and dbname — the same
	// shape generated by CloudNativePG.
	// +optional
	External *ExternalDatabaseSpec `json:"external,omitempty"`
}

// CNPGDatabaseSpec references a CloudNativePG Cluster resource.
type CNPGDatabaseSpec struct {
	// clusterName is the name of an existing CloudNativePG Cluster in the
	// same namespace as the Zabbix resource.
	// +required
	ClusterName string `json:"clusterName"`
}

// ExternalDatabaseSpec references a user-provided database Secret.
type ExternalDatabaseSpec struct {
	// secretName is the name of a Secret (same namespace) containing the
	// PostgreSQL connection details under the keys host, port, user,
	// password, and dbname.
	// +required
	SecretName string `json:"secretName"`
}

// ImageSpec overrides the container image of a component. By default the
// official images are used with the tag derived from spec.version
// (e.g. zabbix/zabbix-server-pgsql:ubuntu-8.0).
type ImageSpec struct {
	// repository replaces the default image repository.
	// +optional
	Repository string `json:"repository,omitempty"`

	// tag replaces the tag derived from spec.version.
	// +optional
	Tag string `json:"tag,omitempty"`

	// pullPolicy is the image pull policy.
	// +kubebuilder:validation:Enum=Always;IfNotPresent;Never
	// +optional
	PullPolicy corev1.PullPolicy `json:"pullPolicy,omitempty"`
}

// ServerSpec configures the Zabbix server. Native high availability is
// enabled by setting replicas greater than 1; all server replicas share
// the database selected in spec.database.
type ServerSpec struct {
	// replicas is the number of Zabbix server pods. 1 runs the server in
	// standalone mode; more than 1 enables native HA (one active node,
	// the rest standby, heartbeat and failover handled by Zabbix).
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the server container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the server container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// agent configures the Zabbix agent 2 sidecar running in each server
	// pod (self-monitoring). Enabled by default.
	// +optional
	Agent *AgentSidecarSpec `json:"agent,omitempty"`
}

// AgentSidecarSpec configures the agent 2 sidecar.
type AgentSidecarSpec struct {
	// enabled runs an agent 2 sidecar in each server pod.
	// +optional
	Enabled *bool `json:"enabled,omitempty"`

	// image overrides the agent 2 sidecar image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`
}

// APISpec configures how the operator reaches the Zabbix API (served by
// the frontend at /api_jsonrpc.php) for control-plane operations such as
// server HA node state observation.
type APISpec struct {
	// tokenSecretRef references a Secret (same namespace) whose key holds
	// a Zabbix API token. The token must belong to a user with permission
	// to read HA node state (hanode.get). Create it in the frontend under
	// Users → API tokens. Required when server.replicas > 1.
	// +required
	TokenSecretRef corev1.SecretKeySelector `json:"tokenSecretRef"`
}

// FrontendSpec configures the Zabbix frontend.
type FrontendSpec struct {
	// replicas is the number of frontend pods.
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the frontend container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the frontend container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`

	// env exposes additional environment variables to the frontend
	// container (e.g. PHP settings).
	// +optional
	Env []corev1.EnvVar `json:"env,omitempty"`

	// service configures the Service fronting the frontend (the
	// user-facing entry). In-cluster access is a ClusterIP Service by
	// default; external exposure (NodePort/LoadBalancer) is opt-in. Any
	// ingress routing on top stays user-managed: the operator owns the
	// Service, not the traffic stack above it.
	// +optional
	Service *FrontendServiceSpec `json:"service,omitempty"`
}

// FrontendServiceSpec configures the frontend Service.
type FrontendServiceSpec struct {
	// type is the exposure of the frontend Service. ClusterIP (the
	// default) serves in-cluster traffic only; NodePort and LoadBalancer
	// expose the frontend outside the cluster (the assigned NodePort is
	// allocation-controlled by the cluster, not pinned here).
	// +kubebuilder:validation:Enum=ClusterIP;NodePort;LoadBalancer
	// +optional
	Type *corev1.ServiceType `json:"type,omitempty"`

	// annotations are added to the frontend Service (e.g. cloud
	// load-balancer settings).
	// +optional
	Annotations map[string]string `json:"annotations,omitempty"`
}

// WebServiceSpec configures the Zabbix web service, which the server uses
// to generate scheduled reports.
type WebServiceSpec struct {
	// replicas is the number of web service pods.
	// +kubebuilder:validation:Minimum=1
	// +optional
	Replicas *int32 `json:"replicas,omitempty"`

	// image overrides the web service container image.
	// +optional
	Image *ImageSpec `json:"image,omitempty"`

	// resources for the web service container.
	// +optional
	Resources corev1.ResourceRequirements `json:"resources,omitempty"`
}

// ZabbixSpec defines the desired state of Zabbix.
// +kubebuilder:validation:XValidation:message="api.tokenSecretRef is required when server.replicas > 1: HA mode needs the Zabbix API for active-node routing",rule="!(has(self.server) && has(self.server.replicas) && self.server.replicas > 1) || (has(self.api) && has(self.api.tokenSecretRef))"
type ZabbixSpec struct {
	// version is the Zabbix release to deploy (e.g. "8.0" or "7.0"). It
	// selects the official container image tags and must match the
	// database schema version.
	// +kubebuilder:validation:Pattern=`^[0-9]+\.[0-9]+$`
	// +required
	Version string `json:"version"`

	// database selects the PostgreSQL database backing this deployment.
	// +required
	Database DatabaseSpec `json:"database"`

	// server configures the Zabbix server.
	// +optional
	Server ServerSpec `json:"server,omitempty"`

	// api configures the operator's access to the Zabbix API. Required
	// when the server runs in HA mode (server.replicas > 1): the operator
	// maintains active-node routing from the HA node state.
	// +optional
	API *APISpec `json:"api,omitempty"`

	// frontend configures the Zabbix frontend. Deployed by default.
	// +optional
	Frontend *FrontendSpec `json:"frontend,omitempty"`

	// webService configures the Zabbix web service. Deployed by default.
	// +optional
	WebService *WebServiceSpec `json:"webService,omitempty"`
}

// HANodeStatus is the observed state of one Zabbix server HA node.
type HANodeStatus struct {
	// name is the HA node name (the server pod name in standalone-to-HA
	// transitions managed by the operator).
	// +required
	Name string `json:"name"`

	// status is the Zabbix-reported node status: active, standby,
	// unavailable, stopped, or unknown (a status code outside the
	// documented registry values; never routed to the active Service).
	// +kubebuilder:validation:Enum=active;standby;unavailable;stopped;unknown
	// +required
	Status string `json:"status"`

	// address is the node address as registered in the HA cluster.
	// +optional
	Address string `json:"address,omitempty"`
}

// ServerHAStatus is the observed state of the server HA cluster.
type ServerHAStatus struct {
	// activeNode is the name of the currently active HA node.
	// +optional
	ActiveNode string `json:"activeNode,omitempty"`

	// nodes lists all HA nodes known to the cluster.
	// +optional
	Nodes []HANodeStatus `json:"nodes,omitempty"`
}

// ComponentConditionType is a custom condition type on the Zabbix resource.
type ComponentConditionType string

const (
	// ConditionReady indicates the deployment as a whole is deployed and
	// all its components are ready.
	ConditionReady ComponentConditionType = "Ready"

	// ConditionDatabaseReady indicates the selected database is reachable.
	ConditionDatabaseReady ComponentConditionType = "DatabaseReady"

	// ConditionServerReady indicates the server workload is deployed and
	// its pods are healthy.
	ConditionServerReady ComponentConditionType = "ServerReady"

	// ConditionFrontendReady indicates the frontend workload is deployed
	// and its pods are healthy.
	ConditionFrontendReady ComponentConditionType = "FrontendReady"

	// ConditionWebServiceReady indicates the web service workload is
	// deployed and its pods are healthy.
	ConditionWebServiceReady ComponentConditionType = "WebServiceReady"
)

// ZabbixStatus defines the observed state of Zabbix.
type ZabbixStatus struct {
	// observedGeneration is the generation most recently observed by the
	// controller.
	// +optional
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`

	// conditions represent the current state of the Zabbix resource.
	// Custom condition types: DatabaseReady, ServerReady, FrontendReady,
	// WebServiceReady.
	// +listType=map
	// +listMapKey=type
	// +optional
	Conditions []metav1.Condition `json:"conditions,omitempty"`

	// serverHA reports the observed state of the server HA cluster
	// (empty when the server runs in standalone mode).
	// +optional
	ServerHA *ServerHAStatus `json:"serverHA,omitempty"`
}

