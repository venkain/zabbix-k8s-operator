// +kubebuilder:subresource:status
// +kubebuilder:resource:scope=Namespaced,shortName={zbx}
// +kubebuilder:printcolumn:name="Version",type=string,JSONPath=`.spec.version`
// +kubebuilder:printcolumn:name="Database",type=string,JSONPath=`.spec.database.cnpg.clusterName`
// +kubebuilder:printcolumn:name="Server Replicas",type=integer,JSONPath=`.spec.server.replicas`
