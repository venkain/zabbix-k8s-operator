package zabbix

import (
	"context"
	"fmt"

	corev1 "k8s.io/api/core/v1"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"

	zabbixv1alpha1 "github.com/venkain/zabbix-k8s-operator/api/v1alpha1"
)

// Secret keys carrying PostgreSQL connection details. This is the shape
// generated by CloudNativePG for the app user (Secret <clusterName>-app),
// which external-database Secrets must follow as well.
const (
	SecretKeyHost     = "host"
	SecretKeyPort     = "port"
	SecretKeyUser     = "user"
	SecretKeyPassword = "password"
	SecretKeyDBName   = "dbname"
)

// DatabaseEnv holds resolved PostgreSQL connection details, ready to be
// injected as environment variables into the components that need them.
type DatabaseEnv struct {
	secretName string

	Host     string
	Port     string
	User     string
	Password string
	DBName   string
}

// SecretName is the Secret the connection details were read from; it is
// watched by the controller so credential rotations trigger reconciliation.
func (d *DatabaseEnv) SecretName() string { return d.secretName }

// ServerEnvVars renders the database environment for the Zabbix server
// and proxies (official image variable names).
func (d *DatabaseEnv) ServerEnvVars() []corev1.EnvVar {
	return []corev1.EnvVar{
		{Name: "DB_SERVER_HOST", Value: d.Host},
		{Name: "DB_SERVER_PORT", Value: d.Port},
		{Name: "POSTGRES_USER", Value: d.User},
		{Name: "POSTGRES_PASSWORD", Value: d.Password},
		{Name: "POSTGRES_DB", Value: d.DBName},
	}
}

// FrontendEnvVars renders the database environment for the frontend
// (official image variable names for zabbix-web-nginx-pgsql).
func (d *DatabaseEnv) FrontendEnvVars() []corev1.EnvVar {
	return []corev1.EnvVar{
		{Name: "DB_SERVER_HOST", Value: d.Host},
		{Name: "DB_SERVER_PORT", Value: d.Port},
		{Name: "POSTGRES_USER", Value: d.User},
		{Name: "POSTGRES_PASSWORD", Value: d.Password},
		{Name: "POSTGRES_DB", Value: d.DBName},
	}
}

// ResolveDatabase reads the connection details selected by spec.database:
// the app-user Secret of a CloudNativePG Cluster (preferred), or a
// user-provided Secret with the same key shape.
func ResolveDatabase(ctx context.Context, c client.Reader, namespace string, spec zabbixv1alpha1.DatabaseSpec) (*DatabaseEnv, error) {
	var secretName string
	switch {
	case spec.CNPG != nil:
		secretName = spec.CNPG.ClusterName + "-app"
	case spec.External != nil:
		secretName = spec.External.SecretName
	default:
		return nil, fmt.Errorf("spec.database: exactly one of cnpg or external must be set")
	}

	var secret corev1.Secret
	if err := c.Get(ctx, types.NamespacedName{Namespace: namespace, Name: secretName}, &secret); err != nil {
		return nil, fmt.Errorf("database secret %s/%s: %w", namespace, secretName, err)
	}

	env := DatabaseEnv{secretName: secretName}
	var missing []string
	for _, req := range []struct {
		key string
		dst *string
	}{
		{SecretKeyHost, &env.Host},
		{SecretKeyPort, &env.Port},
		{SecretKeyUser, &env.User},
		{SecretKeyPassword, &env.Password},
		{SecretKeyDBName, &env.DBName},
	} {
		value, ok := secret.Data[req.key]
		if !ok || len(value) == 0 {
			missing = append(missing, req.key)
			continue
		}
		*req.dst = string(value)
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("database secret %s/%s is missing keys: %v", namespace, secretName, missing)
	}

	return &env, nil
}
